uint16_t wildSwarmShare(uint8_t i);
// Today's swarm in `region` (an index into WILD_SWARMS), or -1.
int wildSwarmToday(uint8_t region, const Pet &p);
// Today's swarm if it is in `area` and can be met (art, pack), else -1.
