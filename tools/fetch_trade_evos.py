#!/usr/bin/env python3
"""Writes tools/dex_trade.py: every evolution that happens by TRADE, from PokeAPI.

  python3 tools/fetch_trade_evos.py

Reads PokeAPI's data dump (pokemon_evolution.csv and pokemon_species.csv in the
PokeAPI/pokeapi repository) rather than the REST API, for the same reasons as
fetch_weights.py: two files instead of hundreds of requests, and pokeapi.co
itself may be unreachable where this is run.

This game has no held items, so a trade that needs one (Onix holding a Metal
Coat) counts as a plain trade. Two rules decide what is included:

  - A target that the real games ALSO reach by levelling up (Milotic, by
    beauty) is left out: it keeps its level route here, and making it
    trade-only would take away something a one-board player has today.
  - A trade that needs a specific PARTNER (Karrablast for Shelmet) keeps it.
    gen_dex.py emits it, and Pet::markTraded() checks it.

Fails loudly rather than writing a partial table.
"""
import csv
import io
import os
import re
import subprocess
import sys

BASE = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'dex_trade.py')
TRIGGER_LEVEL_UP, TRIGGER_TRADE = '1', '2'

_dexh = open(os.path.join(HERE, '..', 'dex.h')).read()
DEX_COUNT = int(re.search(r'#define DEX_COUNT (\d+)', _dexh).group(1))


def fetch(name):
    # curl, not urllib: see fetch_weights.py
    raw = subprocess.run(['curl', '-sSfL', BASE + name], check=True,
                         capture_output=True).stdout.decode('utf-8')
    return list(csv.DictReader(io.StringIO(raw)))


def main():
    species = {int(r['id']): r for r in fetch('pokemon_species.csv')}
    rows = fetch('pokemon_evolution.csv')
    by_target = {}
    for r in rows:
        by_target.setdefault(int(r['evolved_species_id']), []).append(r)

    evos = set()
    skipped = []
    for r in rows:
        if r['evolution_trigger_id'] != TRIGGER_TRADE:
            continue
        to = int(r['evolved_species_id'])
        frm = species[to]['evolves_from_species_id']
        if not frm:
            sys.exit(f'trade target {to} has no pre-evolution -- not writing')
        frm = int(frm)
        if to > DEX_COUNT or frm > DEX_COUNT:
            continue
        if any(o['evolution_trigger_id'] == TRIGGER_LEVEL_UP for o in by_target[to]):
            skipped.append(species[to]['identifier'])
            continue
        partner = int(r['trade_species_id']) if r['trade_species_id'] else 0
        evos.add((frm, to, partner))

    if len(evos) < 20:
        sys.exit(f'only {len(evos)} trade evolutions found -- a partial fetch? not writing')
    lines = ['# GENERATED by tools/fetch_trade_evos.py from PokeAPI - do not edit\n',
             '# (from, to, partner): `from` evolves into `to` when traded; partner is\n',
             '# the species it must be traded FOR, or 0 for any.\n',
             'TRADE_EVOS = [\n']
    lines += [f'    ({a}, {b}, {p}),  # {species[a]["identifier"]} -> {species[b]["identifier"]}\n'
              for a, b, p in sorted(evos)]
    lines.append(']\n')
    open(OUT, 'w').write(''.join(lines))
    print(f'wrote {OUT}: {len(evos)} trade evolutions; left on their level route: {skipped}')


if __name__ == '__main__':
    main()
