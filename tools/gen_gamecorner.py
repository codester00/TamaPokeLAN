#!/usr/bin/env python3
"""Game Corner and Surfing Pikachu art: pret disassemblies -> gamecorner_art.h

    python3 tools/gen_gamecorner.py

SOURCE AND LICENCE -- read CREDITS.md before publishing anything built from
this. Like tools/gen_avatars.py, this takes Nintendo / Game Freak artwork from
the pret disassemblies (pokered, pokecrystal, pokeyellow). It is NOT licensed
for redistribution the way the PMD sprites (CC BY-NC) are; it is here because
the project owner asked for the real art (2026-10-22), and CREDITS.md says so.

What is taken, and how each sheet is laid out (the layouts were read from the
engine code, not guessed):

- pokered gfx/slots/red_slots_2.png: Red's six reel symbols. 4 tiles a symbol,
  one PNG row each, in the order BOTTOM-LEFT, BOTTOM-RIGHT, TOP-LEFT, TOP-RIGHT:
  SLOTS7 EQU $0200 (constants/script_constants.asm) puts tiles 0-1 on the
  bottom row, and SlotMachine_AnimWheel draws a wheel bottom-up.
- pokecrystal gfx/slots/slots_2.png: Crystal's reel symbols, 16x16 each, in
  SLOTS_* order (7, POKE BALL, CHERRY, PIKACHU, SQUIRTLE, STARYU).
- pokecrystal gfx/card_flip/card_flip_2.png: the four card pictures, 3x3 tiles
  each, from tile 24 on. CardFlip_DisplayCardFaceUp's .Deck anchors ($4e, $57,
  $69, $60) put the creatures in the order PIKACHU, JIGGLYPUFF, POLIWAG,
  ODDISH -- which in the sheet are faces 0, 1, 3, 2.
- pokeyellow gfx/surfing_pikachu/surfing_pikachu_1b.png: Pikachu on the board,
  24x24 frames, for Surfing Pikachu (see SURF_FRAMES).

Every image is 2bpp greyscale; shades are stored as indices 0-3 (0 = black,
3 = white) into a small RGB565 palette per set. 0xFF is transparent.
"""
import os
import subprocess
import sys
import tempfile

try:
    from PIL import Image
except ImportError:
    sys.exit('needs Pillow (pip install pillow)')

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'gamecorner_art.h')
RAW = 'https://raw.githubusercontent.com/pret/%s/master/%s'


def fetch(repo, path):
    d = tempfile.mkdtemp()
    f = os.path.join(d, os.path.basename(path))
    subprocess.run(['curl', '-sfL', RAW % (repo, path), '-o', f], check=True)
    return Image.open(f).convert('L')


def shade(v):
    # 2bpp greyscale exported by pret: 0, 85, 170, 255 (black .. white)
    return min(3, (v + 42) // 85)


def block(im, x, y, w, h, transparent_white=False):
    out = []
    for r in range(h):
        for c in range(w):
            s = shade(im.getpixel((x + c, y + r)))
            out.append(0xFF if transparent_white and s == 3 else s)
    return out


def red_reels():
    im = fetch('pokered', 'gfx/slots/red_slots_2.png')
    syms = []
    for s in range(6):
        t = [block(im, c * 8, s * 8, 8, 8) for c in range(4)]
        bl, br, tl, tr = t
        px = []
        for r in range(16):
            top = r < 8
            rr = r % 8
            left = tl if top else bl
            right = tr if top else br
            px += left[rr * 8:rr * 8 + 8] + right[rr * 8:rr * 8 + 8]
        syms.append(px)
    return syms


def crystal_reels():
    im = fetch('pokecrystal', 'gfx/slots/slots_2.png')
    return [block(im, 0, s * 16, 16, 16) for s in range(6)]


def cards():
    im = fetch('pokecrystal', 'gfx/card_flip/card_flip_2.png')
    faces = [block(im, 0, 64 + i * 24, 24, 24) for i in range(4)]
    return [faces[0], faces[1], faces[3], faces[2]]   # game order, see above


# Surfing Pikachu: surfing_pikachu_1b.png holds 24x24 frames (3x3 tiles), five
# to a row. The first row is Pikachu on the board at five angles, nose up to
# nose down -- the game picks one by the slope of the wave under it, and so
# does ours (frame 2 is level).
SURF_FRAMES = [(c, 0) for c in range(5)]


def surf():
    im = fetch('pokeyellow', 'gfx/surfing_pikachu/surfing_pikachu_1b.png')
    return [block(im, c * 24, r * 24, 24, 24, transparent_white=True) for c, r in SURF_FRAMES]


def emit(f, name, frames, w, h):
    f.write('static const uint8_t %s[%d][%d] = {\n' % (name, len(frames), w * h))
    for fr in frames:
        f.write('  {\n')
        for r in range(h):
            f.write('    ' + ', '.join('0x%02X' % v for v in fr[r * w:(r + 1) * w]) + ',\n')
        f.write('  },\n')
    f.write('};\n\n')


def main():
    with open(OUT, 'w') as f:
        f.write('// GENERATED by tools/gen_gamecorner.py from pret/pokered, pokecrystal\n'
                '// and pokeyellow - do not edit. See CREDITS.md: Nintendo / Game Freak\n'
                '// artwork from the disassemblies, not licensed material.\n'
                '#pragma once\n#include <stdint.h>\n\n'
                '// Shade 0 = black .. 3 = white; 0xFF = transparent. Palettes are\n'
                '// RGB565, one per set, in the spirit of the GBC colourings.\n'
                'static const uint16_t GC_RED_PAL[4] = { 0x18C4, 0xD8A7, 0xFD34, 0xFFFF };\n'
                'static const uint16_t GC_GS_PAL[4] = { 0x18C4, 0x4C98, 0xA6FD, 0xFFFF };\n'
                'static const uint16_t GC_CARD_PAL[4] = { 0x18C4, 0x7BEF, 0xFEA0, 0xFFFF };\n'
                'static const uint16_t GC_SURF_PAL[4] = { 0x18C4, 0xFEA0, 0xFFF0, 0xFFFF };\n\n'
                '#define GC_REEL_PX 16\n#define GC_CARD_PX 24\n#define GC_SURF_PX 24\n#define GC_SURF_FRAMES 5\n\n')
        emit(f, 'GC_RED_REEL', red_reels(), 16, 16)
        emit(f, 'GC_GS_REEL', crystal_reels(), 16, 16)
        emit(f, 'GC_CARD', cards(), 24, 24)
        emit(f, 'GC_SURF', surf(), 24, 24)
    print('wrote', os.path.relpath(OUT))


if __name__ == '__main__':
    main()
