def block_safari(g):
    """Each Safari species: the throw pattern that catches it most often over an
    encounter's 30 Safari Balls, measured with the firmware's own Safari rules
    (guide_data.cpp plays 20,000 encounters per pattern)."""
    out = []
    by_area = defaultdict(list)
    for s in g.d['safari']:
        by_area[s['a']].append(s)
    for a in sorted(by_area):
        A = g.areas[a]
        rows = by_area[a]
        out.append('**%s** (%s)' % (A['n'], g.region_name(A['r'])))
        out.append('')
        out.append('| Pokemon | Balls only | Best pattern | Its odds |')
        out.append('|---|---|---|---|')
        for s in sorted(rows, key=lambda s: s['odds'][0][1]):
            if not g.dex[s['d']]['art']:
                continue
            best = max(s['odds'], key=lambda o: o[1])
            if best[1] < s['odds'][0][1] + 2:
                best = s['odds'][0]
            out.append('| %s | %.0f%% | %s | %.0f%% |' % (g.name(s['d']), s['odds'][0][1],
                                                          best[0], best[1]))
        out.append('')
    return '\n'.join(out).rstrip()


BLOCKS = {'safari': block_safari, 'typechart': block_typechart, 'mart': block_mart, 'zone': block_zone,
          'drops': block_drops, 'counts': block_counts, 'regions': block_regions}


def fill_blocks(text, g):
    def rep(m):
        name = m.group(1)
        if name not in BLOCKS:
            raise SystemExit('gen_guide: unknown block %r' % name)
        return '<!-- BEGIN GENERATED: %s -->\n%s\n<!-- END GENERATED: %s -->' % (
            name, BLOCKS[name](g), name)
    return re.sub(r'<!-- BEGIN GENERATED: (\w+) -->.*?<!-- END GENERATED: \1 -->', rep, text,
                  flags=re.S)


def check_prices(text, g):
    """An amount quoted right after an item's name must be its price."""
    bad = []
    plain = re.sub(r'<!-- BEGIN GENERATED: (\w+) -->.*?<!-- END GENERATED: \1 -->', '', text,
                   flags=re.S)
    prices = {}
    for it in g.items[1:]:
        prices[title(it[0]).lower()] = (it[5], it[6])
    zone = {g.item(k).lower(): bp for k, bp in g.d['zonePrizes']}
    for name, (buy, sell) in prices.items():
        for m in re.finditer(re.escape(name) + r'[^.$\n|]{0,24}?\(?\$([\d,]+)', plain, re.I):
            v = int(m.group(1).replace(',', ''))
            if v not in (buy, sell):
                bad.append('%s quoted at $%d, the game says $%d (sells $%d)' % (name, v, buy, sell))
    for name, bp in zone.items():
        for m in re.finditer(re.escape(name) + r'[^.\n|]{0,24}?(\d+) BP', plain, re.I):
            if int(m.group(1)) != bp:
                bad.append('%s quoted at %s BP, the counter says %d' % (name, m.group(1), bp))
    return bad


def main():
    check = '--check' in sys.argv
    g = Game(load())
    files = {}
    for r in range(9):
        files[os.path.join(OUTDIR, REGION_FILES[r] + '.md')] = region_chapter(g, r)
    files[os.path.join(OUTDIR, 'every-pokemon.md')] = every_pokemon(g)
    files[os.path.join(OUTDIR, 'tms.md')] = tms_page(g)
    guide = open(GUIDE).read()
    files[GUIDE] = fill_blocks(guide, g)
    problems = check_prices(files[GUIDE], g)
    if check:
        for path, text in files.items():
            old = open(path).read() if os.path.exists(path) else ''
            if old != text:
                problems.append('%s is out of date: run python3 tools/gen_guide.py'
                                % os.path.relpath(path, ROOT))
        for p in problems:
            print('gen_guide:', p)
        if problems:
            sys.exit(1)
        print('gen_guide: the guide matches the firmware')
        return
    os.makedirs(OUTDIR, exist_ok=True)
    for path, text in files.items():
        with open(path, 'w') as f:
            f.write(text)
    for p in problems:
        print('gen_guide: WARNING', p)
    print('gen_guide: wrote %d files' % len(files))


if __name__ == '__main__':
    main()
