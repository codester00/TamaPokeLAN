def region_chapter(g, r):
    out = [HEADER.rstrip(), '']
    rn = g.region_name(r)
    areas = [a for a, A in enumerate(g.areas) if A['r'] == r]
    out.append('# %s' % rn)
    out.append('')
    out.append('[Back to the guide](../players-guide.md#part-2-walkthrough-and-strategy)')
    out.append('')
    out.append('%s has %d Explore areas and a ladder of 8 %s, 4 Elite Four seats and a champion. '
               'Its areas come from %s.' % (
                   rn, len(areas), 'trials' if r == 6 else 'gyms', GAMES[r]))
    out.append('')
    out.append('How to read the tables: **Chance** is the share of that area\'s encounters, '
               'once the whole story is open. **Level** is what you meet. A Pokemon marked '
               '*later in the story* shows up only after more badges. '
               + ('Johto, Sinnoh and Paldea change with the clock: morning is 04:00-10:00, '
                  'day 10:00-18:00, night 18:00-04:00 (a board with no clock counts as day). '
                  if r in HAS_TIME else ''))
    out.append('')

    # the ladder at a glance
    out.append('## The ladder at a glance')
    out.append('')
    out.append('| # | Trainer | Where | Type | Levels | Earns |')
    out.append('|---|---|---|---|---|---|')
    for s, T in enumerate(g.ladders[r]):
        lv = [m['lv'] for m in T['team']]
        earns = title(g.badges[r][s]) if s < 8 else ('League seat' if s < 12 else 'the title')
        out.append('| %d | %s | %s | %s | %d-%d | %s |' % (
            s + 1, title(T['n']), title(T['place']), g.types[T['type']], min(lv), max(lv), earns))
    out.append('')

    legends = [L for L in g.d['legends'] if g.areas[L['a']]['r'] == r]
    fixed = [F for F in g.d['fixed'] if g.areas[F['a']]['r'] == r]
    swarms = [S for S in g.d['swarms'] if g.areas[S['a']]['r'] == r]
    halls = [h for h in g.d['halls'] if h['r'] == r and h['prizes']]

    def notes_for(a):
        n = []
        for L in legends:
            if L['a'] == a:
                s = '**Legendary: %s**, level %d, %s.' % (g.name(L['d']), L['lv'],
                                                         g.gate_name(r, L['gate']))
                if L['roams']:
                    s += ' After your first meeting it roams the whole region.'
                if L['needs']:
                    s += ' Only once %s are all caught.' % ', '.join(g.name(x) for x in L['needs'])
                n.append(s)
        for F in fixed:
            if F['a'] == a:
                s = '**One-off: %s**, level %d, %s.' % (g.name(F['d']), F['lv'],
                                                       g.gate_name(r, F['gate']))
                if F['days'] != 0x7F:
                    s += ' Only on ' + ', '.join(WEEKDAYS[i] for i in range(7) if F['days'] >> i & 1) + 's.'
                if F['shiny']:
                    s += ' Always shiny.'
                n.append(s)
        for S in swarms:
            if S['a'] == a:
                n.append('**Swarm days: %s** takes about %d%% of encounters on the days it swarms '
                         '(the row says SWARM)%s.' % (
                             g.name(S['d']), round(S['share'] / 10),
                             ', ' + g.gate_name(r, S['gate']) if S['gate'] > g.areas[a]['gate'] else ''))
        return n

    gates = sorted({A['gate'] for A in g.areas if A['r'] == r} | set(range(0, 9)) | {GATE_CHAMPION})
    for gate in gates:
        opened = [a for a in areas if g.areas[a]['gate'] == gate]
        if gate == 0:
            out.append('## Before the first %s' % ('trial' if r == 6 else 'badge'))
        elif gate >= GATE_CHAMPION:
            out.append('## After the champion')
        elif gate > 8:
            out.append('## After %s' % title(g.ladders[r][gate - 1]['n']))
        else:
            out.append('## With the %s' % title(g.badges[r][gate - 1]))
        out.append('')
        hall_here = [h for h in halls if h['gate'] == gate]
        if opened:
            out.append('New areas: ' + ', '.join('**%s**' % g.areas[a]['n'] for a in opened) + '.')
            out.append('')
            for a in opened:
                out += area_section(g, a, notes_for(a))
        for h in hall_here:
            out.append('#### %s' % h['n'])
            out.append('A Game Corner, opening %s, in the area list: coins, slots%s and a prize '
                       'counter. See [the side games](../players-guide.md#the-side-games).' % (
                           g.gate_name(r, gate), ' and card flip' if h['cards'] else ''))
            out.append('')
            out.append('| Prize | Coins |')
            out.append('|---|---|')
            for kind, what, lv, price in h['prizes']:
                p = ('%s, level %d' % (g.name(what), lv)) if kind == 0 else ('TM ' + g.move(what))
                out.append('| %s | %s |' % (p, format(price, ',')))
            out.append('')
        if gate < 8:
            out += leader_section(g, r, gate)
        elif gate == 8:
            out.append('### The Pokemon League')
            out.append('')
            out.append('The four Elite Four seats and the champion are one run: HP comes back for '
                       'every fight, PP does not, and you cannot put your Pokemon to bed until '
                       'it ends. See [the League](../players-guide.md#9-gyms-and-the-pokemon-league).')
            out.append('')
            for s in range(8, 13):
                out += leader_section(g, r, s)
    return '\n'.join(out).rstrip() + '\n'


def every_pokemon(g):
    d = g.d
    wild = defaultdict(list)    # species -> [(chance, area)]
    for a, A in enumerate(g.areas):
        for dexno, v in area_rows(g, a).items():
            p = max(v['m'], v['d'], v['n'])
            if p:
                wild[dexno].append((p, a))
    special = defaultdict(list)
    for L in d['legends']:
        A = g.areas[L['a']]
        special[L['d']].append('legendary: %s (%s), level %d, %s%s' % (
            A['n'], g.region_name(A['r']), L['lv'], g.gate_name(A['r'], L['gate']),
            ', roams' if L['roams'] else ''))
    for F in d['fixed']:
        A = g.areas[F['a']]
