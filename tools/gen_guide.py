#!/usr/bin/env python3
"""The player's guide's generated half.

    python3 tools/gen_guide.py           # rebuild, then write the guide
    python3 tools/gen_guide.py --check   # fail if anything committed has drifted

Every list in the guide that comes from the game's data is written here, from
the firmware's own tables and rules (tools/emu/guide_data.cpp dumps them as
JSON), so the guide cannot drift from the game -- CLAUDE.md: derive, never
restate. It writes:

  docs/players-guide/<region>.md       the nine walkthrough chapters
  docs/players-guide/every-pokemon.md  all 1025 and the best way to each
  docs/players-guide/tms.md            every TM and where it comes from
  docs/players-guide.md                only the blocks between
                                       <!-- BEGIN GENERATED: x --> and
                                       <!-- END GENERATED: x -->; the rest of
                                       that file is written by hand

--check also reads the hand-written text: a dollar, coin or BP amount quoted
next to an item's name has to be that item's price.

The hidden rules stay hidden here too (docs/guide-notes.md): a catch that waits
for the best rod or Galar's water mode is shown as "later in the story", never
why. The spoiler section of the hand-written guide is the one place that says.
"""
import json
import os
import re
import subprocess
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EMU = os.path.join(ROOT, 'tools', 'emu')
GUIDE = os.path.join(ROOT, 'docs', 'players-guide.md')
OUTDIR = os.path.join(ROOT, 'docs', 'players-guide')
HEADER = ('<!-- GENERATED by tools/gen_guide.py from the firmware\'s own data -- '
          'do not edit; re-run the script. -->\n\n')

WHEN_MORN, WHEN_DAY, WHEN_NITE = 1, 2, 4
WX_AVG, WX_ANY = 0x200, 0x3FF
GATE_CHAMPION = 13
REGION_FILES = ['kanto', 'johto', 'hoenn', 'sinnoh', 'unova', 'kalos', 'alola', 'galar', 'paldea']
GAMES = {
    0: 'FireRed and LeafGreen (both versions)', 1: 'Crystal', 2: 'Emerald', 3: 'Platinum',
    4: 'Black 2 and White 2 (both versions)', 5: 'X and Y (both versions)',
    6: 'Sun and Moon (both versions)', 7: 'Sword and Shield (both versions)',
    8: 'Scarlet and Violet (both versions)'}
HAS_TIME = {1, 3, 8}           # regions whose areas change with the clock
CAT = ['physical', 'special', 'status']
RARE_BELOW = 50     # ten-thousandths: under 0.5% goes in the 'rarely' line
WEEKDAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']


# ---------------------------------------------------------------- the data --

def core_sources():
    """The firmware sources the test harness links, read from run.sh's CORE so
    the two lists cannot drift (CLAUDE.md: derive, never restate)."""
    run = open(os.path.join(EMU, 'tests', 'run.sh')).read()
    line = re.search(r'^CORE=\((.*)\)$', run, re.M).group(1)
    return [p.replace('$ROOT', ROOT).replace('$EMU', EMU)
            for p in re.findall(r'"([^"]+)"', line)]


def load():
    exe = os.path.join('/tmp', 'tamapoke_guide_data')
    srcs = core_sources()
    cmd = ['g++', '-std=c++17', '-O1', '-w', '-I' + EMU, '-I' + ROOT, '-DSPRITE_DIR=""',
           os.path.join(EMU, 'guide_data.cpp')] + srcs + ['-o', exe]
    subprocess.run(cmd, check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    return json.loads(out)


NAMES = {'NIDORAN H': 'Nidoran (female)', 'NIDORAN M': 'Nidoran (male)', 'LT SURGE': 'Lt. Surge',
         'ELITE 4': 'Elite Four'}


def title(s):
    """PIKACHU -> Pikachu, MR. MIME -> Mr. Mime, HO-OH -> Ho-Oh."""
    if s in NAMES:
        return NAMES[s]
    return re.sub(r"[A-Z0-9']+", lambda m: m.group(0)[0] + m.group(0)[1:].lower(), s)


class Game:
    def __init__(self, d):
        self.d = d
        self.dex = d['dex']
        self.types = [title(t) for t in d['types']]
        self.N = len(self.dex) - 1
        self.badges = d['badges']
        self.ladders = d['ladders']
        self.items = d['items']
        self.moves = d['moves']
        self.areas = d['areas']
        self.stones = [title(s) for s in d['stones']]
        self.prev = defaultdict(list)       # species -> [(from, how)]
        self._evolutions()

    def name(self, x):
        return title(self.dex[x]['n'])

    def item(self, k):
        return title(self.items[k][0])

    def move(self, m):
        return title(self.moves[m][0])

    def typing(self, x):
        t1, t2 = self.dex[x]['t']
        return self.types[t1] + ('/' + self.types[t2] if t2 < 18 and t2 != t1 else '')

    def region_of(self, x):
        for r, R in enumerate(self.d['regions'][:9]):
            if R['lo'] <= x <= R['hi']:
                return r
        return 0

    def region_name(self, r):
        return title(self.d['regions'][r]['n'])

    def gate_name(self, region, gate):
        if gate == 0:
            return 'from the start'
        if gate >= GATE_CHAMPION:
            return 'after the champion'
        if gate <= 8:
            return 'after the ' + title(self.badges[region][gate - 1])
        return 'after ' + title(self.ladders[region][gate - 1]['n'])

    def bst(self, x):
        return sum(self.dex[x]['b'])

    def eff(self, atk, x):
        """x10 multiplier of a move of type atk against species x."""
        t1, t2 = self.dex[x]['t']
        m = self.d['chart'][atk][t1]
        if t2 < 18 and t2 != t1:
            m = m * self.d['chart'][atk][t2] // 10
        return m

    # ---- evolution: where each species comes from, as the firmware rules it
    def _evolutions(self):
        d, dex = self.d, self.dex
        item_from = {(f, t) for f, t, s, g in d['itemEvos']}
        trade_from = {(f, t) for f, t, p in d['tradeEvos']}
        branch_from = {(f, t) for f, t, k, a in d['branchEvos']}
        gender_from = {(f, t) for f, t, fe in d['genderEvos']}
        for f, t, s, g in d['itemEvos']:
            how = 'use a ' + self.stones[s] if s < 10 else 'use the ' + self.stones[s]
            if g == 1:
                how += ' on a male one'
            elif g == 2:
                how += ' on a female one'
            self.prev[t].append((f, how))
        for f, t, p in d['tradeEvos']:
            how = 'trade it, or use a Linking Cord'
            if p:
                how = 'trade it for a %s, or Linking Cord the pair' % self.name(p)
            if f == 366:
                how += ' (which of the two is fixed by the creature)'
            self.prev[t].append((f, how))
        for f, t, k, a in d['branchEvos']:
            lv = dex[f]['lv']
            if k == 0:
                how = 'level %d, your choice of branch' % lv
            elif k == 1:
                how = {1: 'level %d with Attack above Defense',
                       -1: 'level %d with Defense above Attack',
                       0: 'level %d with Attack equal to Defense'}[a] % lv
            elif k == 2:
                how = 'level %d, half of them (fixed by the creature)' % lv
                if f == 790:
                    how = ('level %d: whichever of Solgaleo and Lunala you do not own; '
                           'half and half if neither or both') % lv
            elif k == 3:
                how = 'joins when Nincada evolves, with a spare Poke Ball and room'
            else:
                how = 'walk %d steps while raising it' % (a * 100)
            self.prev[t].append((f, how))
        for f, t, fe in d['genderEvos']:
            self.prev[t].append((f, 'level %d, %s only' % (dex[f]['lv'], 'female' if fe else 'male')))
        eevee = {196: 'bond 40 and two days old, by day (06:00-18:00)',
                 197: 'bond 40 and two days old, by night',
                 700: 'bond 40 and two days old, knowing a Fairy move'}
        for t, how in eevee.items():
            self.prev[t].append((133, how))
        for f in range(1, self.N + 1):
            t = dex[f]['to']
            if not t or (f, t) in item_from or (f, t) in trade_from or (f, t) in branch_from \
               or (f, t) in gender_from or f == 133:
                continue
            self.prev[t].append((f, 'level %d' % dex[f]['lv']))

    def final_forms(self, x, seen=None):
        """Every species x can end up as (x itself if it does not evolve)."""
        outs = [t for t, ps in self.prev.items() for f, h in ps if f == x and t != 292]
        if not outs:
            return [x]
        res = []
        for t in outs:
            for y in self.final_forms(t):
                if y not in res:
                    res.append(y)
        return res


# ---------------------------------------------------------------- areas --

def area_rows(g, a):
    """Per species: chances by band (in WILD_WEIGHT_TOTAL ten-thousandths of the
    area's encounters, the full story open), how much of that waits for later in
    the story, its weathers and its share in each, its level floor. A weather
    area's chances are the all-weather average -- what a board with no clock
    meets, and every day's average."""
    A = g.areas[a]
    rows = {}
    for dexno, w, when, floor, gate, wx in A['slots']:
        r = rows.setdefault(dexno, {'m': 0, 'd': 0, 'n': 0, 'gm': 0, 'gd': 0, 'gn': 0,
                                    'floor': 0, 'wx': 0, 'wxp': [0] * 9})
        ctx = WX_AVG if A['wx'] else WX_ANY
        if wx & ctx or wx == WX_ANY:
            for bit, k in ((WHEN_MORN, 'm'), (WHEN_DAY, 'd'), (WHEN_NITE, 'n')):
                if when & bit:
                    r[k] += w
                    if gate:
                        r['g' + k] += w
        if A['wx'] and wx != WX_ANY:
            r['wx'] |= wx & 0x1FF
            if when & WHEN_DAY:
                for i in range(9):
                    if wx >> i & 1:
                        r['wxp'][i] += w
        r['floor'] = max(r['floor'], floor)
    return rows


def lv_range(A, floor):
    lo, hi = A['lv']
    lo = max(lo, floor)
    hi = max(hi, floor)
    return '%d' % lo if lo == hi else '%d-%d' % (lo, hi)


def pct(w):
    if w <= 0:
        return '-'
    p = w / 100.0
    return '%.1f%%' % p if p < 10 else '%d%%' % round(p)


def area_section(g, a, extra_notes):
    A = g.areas[a]
    r = A['r']
    rows = area_rows(g, a)
    out = []
    head = '#### %s' % A['n']
    out.append(head)
    meta = ['levels %d-%d' % tuple(A['lv'])]
    if A['mode'] == 1:
        meta.append('a **Safari** area: no team, 30 Safari Balls an encounter')
    if A['wx']:
        wxs = [title(g.d['wx'][i]) for i in range(9) if A['wx'] >> i & 1]
        meta.append('one weather a day: ' + ', '.join(wxs))
    if A['stones']:
        meta.append('stones found here: ' + ', '.join(g.stones[s] for s in A['stones']))
    out.append('Opens %s; %s.' % (g.gate_name(r, A['gate']), '; '.join(meta)))
    out.append('')
    for n in extra_notes:
        out.append(n)
        out.append('')
    timed = r in HAS_TIME and any(v['m'] != v['d'] or v['d'] != v['n'] for v in rows.values())
    if timed:
        out.append('| Pokemon | Type | Level | Morning | Day | Night | Notes |')
        out.append('|---|---|---|---|---|---|---|')
    else:
        out.append('| Pokemon | Type | Level | Chance | Notes |')
        out.append('|---|---|---|---|---|')

    def key(item):
        dexno, v = item
        return (-max(v['m'], v['d'], v['n']), g.name(dexno))
    rare = []
    for dexno, v in sorted(rows.items(), key=key):
        top = max(v['m'], v['d'], v['n'])
        later = max(v['gm'], v['gd'], v['gn'])
        if top < RARE_BELOW and len(rows) > 12:
            rare.append(g.name(dexno) + (' (later)' if later == top else ''))
            continue
        notes = []
        if not g.dex[dexno]['art']:
            notes.append('no art yet: not met')
        if later and later >= top:
            notes.append('later in the story')
        elif later:
            notes.append('more of them later in the story')
        if v['wx']:
            all_wx = [i for i in range(9) if A['wx'] >> i & 1]
            mine = [i for i in all_wx if v['wx'] >> i & 1]
            if len(mine) < len(all_wx):
                best = max(mine, key=lambda i: v['wxp'][i])
                notes.append('only in %s (%s on such a day)' % (
                    ', '.join(title(g.d['wx'][i]).lower() for i in mine), pct(v['wxp'][best])))
        if v['floor'] > A['lv'][1]:
            notes.append("above the area's levels")
        cells = [g.name(dexno), g.typing(dexno), lv_range(A, v['floor'])]
        if timed:
            cells += [pct(v['m']), pct(v['d']), pct(v['n'])]
        else:
            cells += [pct(top)]
        cells.append('; '.join(notes))
        out.append('| ' + ' | '.join(cells) + ' |')
    if rare:
        out.append('')
        out.append('Also, rarely (under %s of encounters each): %s.' % (
            pct(RARE_BELOW), ', '.join(rare)))
    out.append('')
    return out


# ---------------------------------------------------------------- leaders --

def leader_advice(g, region, seat, T):
    team = [m['d'] for m in T['team']]
    atk_types = set()
    for m in T['team']:
        for mv in m['m']:
            M = g.moves[mv]
            if M[2] != 2 and M[3] > 0:
                atk_types.add(M[1])
    # offence: how many of the team each type hits hard, less how many resist it
    off = []
    for t in range(18):
        s = sum(1 if g.eff(t, x) > 10 else (-1 if g.eff(t, x) < 10 else 0) for x in team)
        off.append((s, t))
    off.sort(reverse=True)
    best = [t for s, t in off if s > 0][:3]
    # defence: the types their attacks hit hard
    danger = defaultdict(int)
    for t in range(18):
        for at in atk_types:
            if g.d['chart'][at][t] > 10:
                danger[t] += 1
    risky = [t for t in sorted(danger, key=lambda t: -danger[t]) if danger[t] >= 2][:3]
    return best, sorted(atk_types), risky


def catchable_before(g, region, gate):
    """Species met in this region's areas open at `gate`, by base-stat total."""
    seen = {}
    for a, A in enumerate(g.areas):
        if A['r'] != region or A['gate'] > gate or A['mode'] == 1:
            continue
        for dexno, w, when, floor, sg, wx in A['slots']:
            if sg and sg > gate or not g.dex[dexno]['art']:
                continue
            seen[dexno] = A['n']
    return seen


def leader_section(g, region, seat):
    T = g.ladders[region][seat]
    out = []
    kind = (('Trial %d' if region == 6 else 'Gym %d') % (seat + 1) if seat < 8 else
            'Elite Four, seat %d' % (seat - 7) if seat < 12 else 'Champion')
    badge = (' -- the %s' % title(g.badges[region][seat])) if seat < 8 else ''
    place = ' (%s)' % title(T['place']) if seat < 8 else ''
    out.append('#### %s: %s%s%s' % (kind, title(T['n']), place, badge))
    top = max(m['lv'] for m in T['team'])
    out.append('%s specialist. %d Pokemon, best level %d: your team fights at level %d at most, '
               'and on hard you bring %d at most. Prize money: $%s on easy, $%s on hard '
               '(half again for a rematch).' % (
                   g.types[T['type']], len(T['team']), top, top, len(T['team']),
                   format(T['prize'][0], ','), format(T['prize'][1], ',')))
    out.append('')
    out.append('| Pokemon | Type | Level | Moves |')
    out.append('|---|---|---|---|')
    for m in T['team']:
        out.append('| %s | %s | %d | %s |' % (g.name(m['d']), g.typing(m['d']), m['lv'],
                                             ', '.join(g.move(x) for x in m['m']) or '-'))
    out.append('')
    best, atk, risky = leader_advice(g, region, seat, T)
    tips = []
    if best:
        tips.append('**Hit them with** ' + ', '.join(g.types[t] for t in best) + ' moves.')
    if atk:
        tips.append('**Their attacks are** ' + ', '.join(g.types[t] for t in atk) + '.')
    if risky:
        tips.append('**Careful with** ' + ', '.join(g.types[t] for t in risky) +
                    ' Pokemon: several of those attacks hit them hard.')
    seen = catchable_before(g, region, seat)
    picks = []
    for dexno in sorted(seen, key=lambda x: -g.bst(x)):
        t1, t2 = g.dex[dexno]['t']
        if not (set(best[:3]) & {t1, t2}):
            continue
        if any(g.eff(at, dexno) > 10 for at in atk if at in best[:0]):
            continue
        picks.append('%s (%s)' % (g.name(dexno), seen[dexno]))
        if len(picks) == 4:
            break
    if picks and seat < 8:
        tips.append('**Catchable before this fight:** ' + ', '.join(picks) + '.')
    if T['hardTr'] < 100:
        tips.append('On hard this leader trains to %d of 100, a little softer than the rest.'
                    % T['hardTr'])
    out.append(' '.join(tips))
    out.append('')
    return out


