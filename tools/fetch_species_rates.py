#!/usr/bin/env python3
"""Writes tools/dex_rates.py: every species' catch rate and gender rate, from PokeAPI.

  python3 tools/fetch_species_rates.py

Reads PokeAPI's data dump (data/v2/csv/pokemon_species.csv in the
PokeAPI/pokeapi repository) rather than the REST API, the same way
fetch_weights.py does.

- capture_rate is the games' own catch rate, 3 (legendaries) to 255 (Caterpie).
  The Safari ball (wild.cpp) runs the games' catch formula on it.
- gender_rate is the games' eighths of a female: -1 genderless, 0 always male,
  8 always female, anything between has two genders.
- ITEM_EVOS (v3.81), from pokemon_evolution.csv: the evolutions by one of
  EVO_STONES used from the bag. Rows that need a regional form or a region
  (Alolan Ninetales, Hisuian Electrode...) are left out: this dex has no forms.
- GENDER_EVOS (v3.80), from pokemon_evolution.csv: the level-up evolutions
  that depend on the creature's gender -- only those where the genders really
  differ (Burmy splits, only a female Combee or Salandit evolves). Meowstic
  and Oinkologne differ only in form here, so they are left out. Item
  evolutions with a gender (Kirlia's and Snorunt's Dawn Stone) come with the
  stones.

Fails loudly rather than writing a partial table.
"""
import csv
import io
import os
import re
import subprocess
import sys

URL = ('https://raw.githubusercontent.com/PokeAPI/pokeapi/master/'
       'data/v2/csv/pokemon_species.csv')
EVO_URL = ('https://raw.githubusercontent.com/PokeAPI/pokeapi/master/'
           'data/v2/csv/pokemon_evolution.csv')
LEVEL_UP = '1'                     # evolution_triggers.csv
GENDER_NAME = {'1': 'F', '2': 'M'}  # genders.csv
ITEMS_URL = ('https://raw.githubusercontent.com/PokeAPI/pokeapi/master/'
             'data/v2/csv/items.csv')
USE_ITEM = '3'                     # evolution_triggers.csv
# The evolution items this game has, in the order items.h appends them
# (IT_FIRESTONE onwards) -- ITEM_EVOS stores this index, so it is APPEND-ONLY.
EVO_STONES = ['fire-stone', 'water-stone', 'thunder-stone', 'leaf-stone',
              'moon-stone', 'sun-stone', 'shiny-stone', 'dusk-stone',
              'dawn-stone', 'ice-stone', 'black-augurite']
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'dex_rates.py')

# Kept in step with dex.h rather than restated, as gen_moves.py does.
_dexh = open(os.path.join(HERE, '..', 'dex.h')).read()
DEX_COUNT = int(re.search(r'#define DEX_COUNT (\d+)', _dexh).group(1))


def main():
    # curl, not urllib: urllib has no cert store in some environments this
    # project is built in (see check_sprites.py).
    raw = subprocess.run(['curl', '-sSfL', URL], check=True,
                         capture_output=True).stdout.decode('utf-8')
    catch, gender = {}, {}
    for row in csv.DictReader(io.StringIO(raw)):
        sid = int(row['id'])
        if 1 <= sid <= DEX_COUNT:
            catch[sid] = int(row['capture_rate'])
            gender[sid] = int(row['gender_rate'])

    missing = [n for n in range(1, DEX_COUNT + 1) if n not in catch]
    if missing:
        sys.exit(f'no rates for {len(missing)} species, e.g. {missing[:5]} -- not writing')
    bad = [n for n in catch if not 1 <= catch[n] <= 255 or not -1 <= gender[n] <= 8]
    if bad:
        sys.exit(f'rate out of range for {bad[:5]} -- not writing')

    lines = ['# GENERATED by tools/fetch_species_rates.py from PokeAPI - do not edit\n',
             '# dex number -> the games\' catch rate (3..255)\n',
             'CATCH_RATE = {\n']
    lines += [f'    {n}: {catch[n]},\n' for n in range(1, DEX_COUNT + 1)]
    lines.append('}\n\n')
    lines.append('# dex number -> eighths female: -1 genderless, 0 all male, 8 all female\n')
    lines.append('GENDER_RATE = {\n')
    lines += [f'    {n}: {gender[n]},\n' for n in range(1, DEX_COUNT + 1)]
    lines.append('}\n')

    # The gender-decided level-up evolutions.
    evo = subprocess.run(['curl', '-sSfL', EVO_URL], check=True,
                         capture_output=True).stdout.decode('utf-8')
    origin = {int(r['id']): int(r['evolves_from_species_id'] or 0)
              for r in csv.DictReader(io.StringIO(raw))}
    by_from = {}
    for r in csv.DictReader(io.StringIO(evo)):
        if r['gender_id'] and r['evolution_trigger_id'] == LEVEL_UP and not r['trigger_item_id']:
            to = int(r['evolved_species_id'])
            frm = origin[to]
            if to <= DEX_COUNT:
                by_from.setdefault(frm, set()).add(
                    (to, GENDER_NAME[r['gender_id']], int(r['minimum_level'] or 0)))
    rows = []
    for frm, opts in sorted(by_from.items()):
        if {g for _t, g, _l in opts} == {'F', 'M'} and len({t for t, _g, _l in opts}) == 1:
            continue                     # both genders, one species: a form only
        rows += sorted(opts)
    if not rows:
        sys.exit('no gender evolutions found -- not writing')

    # The item evolutions (v3.81).
    items = {r['id']: r['identifier'] for r in csv.DictReader(io.StringIO(
        subprocess.run(['curl', '-sSfL', ITEMS_URL], check=True,
                       capture_output=True).stdout.decode('utf-8')))}
    item_rows = set()
    for r in csv.DictReader(io.StringIO(evo)):
        if r['evolution_trigger_id'] != USE_ITEM:
            continue
        name = items.get(r['trigger_item_id'])
        if name not in EVO_STONES or r['region_id']:
            continue
        to = int(r['evolved_species_id'])
        frm = origin[to]
        # A form other than the species' own default (whose id is the
        # species') is a regional form this dex does not have.
        if r['required_pokemon_form_id'] and int(r['required_pokemon_form_id']) != frm:
            continue
        if r['evolved_pokemon_form_id'] and int(r['evolved_pokemon_form_id']) != to:
            continue
        if frm > DEX_COUNT or to > DEX_COUNT:
            continue
        item_rows.add((frm, to, EVO_STONES.index(name), GENDER_NAME.get(r['gender_id'], '')))
    if len(item_rows) < 45:
        sys.exit(f'only {len(item_rows)} item evolutions -- the parse broke, not writing')
    lines.append('\n# (from, to, gender, level): a level-up evolution only that gender takes\n')
    lines.append('GENDER_EVOS = [\n')
    for to, g, lvl in rows:
        lines.append(f'    ({origin[to]}, {to}, {g!r}, {lvl}),\n')
    lines.append(']\n')
    lines.append('\n# Evolution items, in items.h order (IT_FIRESTONE onwards). APPEND-ONLY.\n')
    lines.append(f'EVO_STONES = {EVO_STONES!r}\n')
    lines.append('\n# (from, to, stone index, gender or \'\'): evolves when that item is used\n')
    lines.append('ITEM_EVOS = [\n')
    for frm, to, st, g in sorted(item_rows):
        lines.append(f'    ({frm}, {to}, {st}, {g!r}),  # {EVO_STONES[st]}\n')
    lines.append(']\n')
    open(OUT, 'w').write(''.join(lines))
    print(f'wrote {OUT}: {len(catch)} species')


if __name__ == '__main__':
    main()
