#!/usr/bin/env python3
"""Indoor battle backgrounds from pret/pokeemerald -> backs_indoor.h

    python3 tools/gen_indoor_backs.py

Emerald draws its trainer battles indoors: the `building` scene in the gym
leader's colours, and the `stadium` scene in each Elite Four member's and the
champion's own colours, plus the Battle Frontier's. This renders those tile
maps (graphics/battle_environment/<scene>/tiles.png + map.bin + <name>.pal) to
the same 240x112 8bpp-indexed format as backs.h, so drawBack() draws them
unchanged. 240x112 is the part of the GBA screen above the text box.

The art is unlicensed Nintendo art, the same arrangement as the trainer avatars
(tools/gen_avatars.py): ship this script rather than the header if the repo is
published. Needs only curl and PIL. Indoor scenes have no night version: a gym
is lit at any hour.
"""
import io
import os
import struct
import subprocess

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'backs_indoor.h')
RAW = 'https://raw.githubusercontent.com/pret/pokeemerald/master/graphics/battle_environment/'
W, H = 240, 112

# INDOOR_* order in the firmware. Append only if a save ever stores one (none does).
SCENES = [
    ('LEADER',   'building', 'leader',          'a gym leader'),
    ('SIDNEY',   'stadium',  'sidney',          'Elite Four, first seat'),
    ('PHOEBE',   'stadium',  'phoebe',          'Elite Four, second seat'),
    ('GLACIA',   'stadium',  'glacia',          'Elite Four, third seat'),
    ('DRAKE',    'stadium',  'drake',           'Elite Four, fourth seat'),
    ('CHAMPION', 'stadium',  'wallace',         'the champion'),
    ('FRONTIER', 'stadium',  'battle_frontier', 'a LAN battle'),
]


def fetch(path):
    return subprocess.run(['curl', '-sSfL', RAW + path], check=True,
                          capture_output=True).stdout


def jasc(data):
    lines = data.decode().split()
    if lines[0] != 'JASC-PAL':
        raise SystemExit('not a JASC palette')
    n = int(lines[2])
    v = list(map(int, lines[3:3 + n * 3]))
    return [tuple(v[i * 3:i * 3 + 3]) for i in range(n)]


def render(scene, palname, cache):
    if scene not in cache:
        tiles = Image.open(io.BytesIO(fetch(scene + '/tiles.png')))
        if tiles.mode != 'P':
            raise SystemExit('%s/tiles.png is not indexed' % scene)
        mp = fetch(scene + '/map.bin')
        if len(mp) != 4096:
            raise SystemExit('%s/map.bin: expected a 64x32 map' % scene)
        cache[scene] = (tiles, struct.unpack('<2048H', mp))
    tiles, mp = cache[scene]
    pal = jasc(fetch('%s/%s.pal' % (scene, palname)))
    tw = tiles.size[0] // 8
    px = tiles.load()
    out = []
    for y in range(H):
        for x in range(W):
            # 64x32 = two 32x32 screen blocks side by side; x < 240 is the first.
            e = mp[(y // 8) * 32 + (x // 8)]
            t, hf, vf, pl = e & 1023, e >> 10 & 1, e >> 11 & 1, e >> 12
            sx, sy = (7 - x % 8) if hf else x % 8, (7 - y % 8) if vf else y % 8
            i = px[(t % tw) * 8 + sx, (t // tw) * 8 + sy]
            # The .pal is loaded at BG palette 2 onwards; index 0 is see-through,
            # and only the backdrop shows through it -- palette 0's colour 0.
            slot = pl - 2
            if i == 0 or not 0 <= slot < len(pal) // 16:
                c = pal[0]
            else:
                c = pal[slot * 16 + i]
            out.append(c)
    return out


def main():
    cache, body, rows, total = {}, [], [], 0
    for name, scene, palname, note in SCENES:
        rgb = render(scene, palname, cache)
        lut, pal, idx = {}, [], []
        for r, g, b in rgb:
            c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            if c not in lut:
                lut[c] = len(pal)
                pal.append(c)
            idx.append(lut[c])
        nm = 'INDOOR_' + name
        total += len(idx) + 2 * len(pal)
        body.append('// %s: %s/%s.pal, for %s' % (name, scene, palname, note))
        body.append('static const uint16_t %s_PAL[%d] = {' % (nm, len(pal)))
        body.append('  ' + ', '.join('0x%04X' % c for c in pal))
        body.append('};')
        body.append('static const uint8_t %s_IDX[%d] = {' % (nm, len(idx)))
        for r in range(0, len(idx), 48):
            body.append('  ' + ','.join(str(v) for v in idx[r:r + 48]) + ',')
        body.append('};')
        body.append('')
        rows.append('  { %s_PAL, %s_IDX, %d, %d, %d },' % (nm, nm, W, H, len(pal)))
    out = ['// GENERATED by tools/gen_indoor_backs.py from pret/pokeemerald - do not edit',
           '#pragma once', '#include "backs.h"', '',
           '// Indoor battle backgrounds, same format as BACKS. Unlicensed Nintendo',
           '// art: see CREDITS.md.', '']
    out += body
    out.append('enum IndoorBack : uint8_t {')
    out += ['  INDOOR_%s,' % s[0] for s in SCENES]
    out.append('  INDOOR_COUNT')
    out.append('};')
    out.append('static const BackScene INDOOR_BACKS[INDOOR_COUNT] = {')
    out += rows
    out.append('};')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('indoor backgrounds: %d, %.1f KB -> %s'
          % (len(SCENES), total / 1024.0, os.path.normpath(OUT)))


if __name__ == '__main__':
    main()
