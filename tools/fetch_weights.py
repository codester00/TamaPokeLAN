#!/usr/bin/env python3
"""Writes tools/dex_weights.py: every species' Pokedex weight, from PokeAPI.

  python3 tools/fetch_weights.py

Reads PokeAPI's own data dump (data/v2/csv/pokemon.csv in the PokeAPI/pokeapi
repository) rather than the REST API: one file instead of 1025 requests, and it
is the same numbers the API serves. Only each species' default form is taken --
that is the one the Pokedex lists. Weight is in hectograms (0.1 kg), the unit
PokeAPI and the games' own data use, so it stays an integer all the way to the
panel.

Fails loudly rather than writing a partial table: a species missing from it
would weigh nothing on the card.
"""
import csv
import io
import os
import re
import subprocess
import sys

URL = ('https://raw.githubusercontent.com/PokeAPI/pokeapi/master/'
       'data/v2/csv/pokemon.csv')
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'dex_weights.py')

# Kept in step with dex.h rather than restated, as gen_moves.py does.
_dexh = open(os.path.join(HERE, '..', 'dex.h')).read()
DEX_COUNT = int(re.search(r'#define DEX_COUNT (\d+)', _dexh).group(1))


def main():
    # curl, not urllib: urllib has no cert store in some environments this
    # project is built in (see check_sprites.py).
    raw = subprocess.run(['curl', '-sSfL', URL], check=True,
                         capture_output=True).stdout.decode('utf-8')
    weights = {}
    for row in csv.DictReader(io.StringIO(raw)):
        if row['is_default'] != '1':
            continue
        sid = int(row['species_id'])
        if 1 <= sid <= DEX_COUNT:
            weights[sid] = int(row['weight'])

    missing = [n for n in range(1, DEX_COUNT + 1) if n not in weights]
    if missing:
        sys.exit(f'no weight for {len(missing)} species, e.g. {missing[:5]} -- not writing')
    bad = [n for n, w in weights.items() if not 1 <= w <= 65535]
    if bad:
        sys.exit(f'weight out of uint16 range for {bad[:5]} -- not writing')

    lines = ['# GENERATED by tools/fetch_weights.py from PokeAPI - do not edit\n',
             '# dex number -> Pokedex weight in hectograms (0.1 kg)\n',
             'WEIGHT_HG = {\n']
    lines += [f'    {n}: {weights[n]},\n' for n in range(1, DEX_COUNT + 1)]
    lines.append('}\n')
    open(OUT, 'w').write(''.join(lines))
    print(f'wrote {OUT}: {len(weights)} species, '
          f'{min(weights.values()) / 10} to {max(weights.values()) / 10} kg')


if __name__ == '__main__':
    main()
